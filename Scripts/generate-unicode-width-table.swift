// Generates Sources/TerminalKitText/GeneratedUnicodeTables.swift from the toolchain's own Unicode properties
// (roadmap 0013, ADR-0024), so a width is one table lookup per scalar instead of four property queries.
//
//   swift Scripts/generate-unicode-width-table.swift > Sources/TerminalKitText/GeneratedUnicodeTables.swift
//   swift-format format --in-place --configuration .swift-format Sources/TerminalKitText/GeneratedUnicodeTables.swift
//
// `UnicodeWidthTableTests` checks every scalar against the same properties, so a toolchain with newer Unicode
// data fails the suite until the table is regenerated.

/// The classes UnicodeWidth needs per scalar, as bits.
func classes(_ value: UInt32) -> UInt8 {
    guard let scalar = Unicode.Scalar(value) else { return 0 }
    let properties = scalar.properties
    var bits: UInt8 = 0
    let residualWide: [ClosedRange<UInt32>] = [
        0x1100 ... 0x115F, 0x2E80 ... 0x303E, 0x3041 ... 0x33BF, 0xA000 ... 0xA4CF, 0xAC00 ... 0xD7AF,
        0xFE30 ... 0xFE6F, 0xFF01 ... 0xFF60, 0xFFE0 ... 0xFFE6
    ]
    if properties.isIdeographic || residualWide.contains(where: { $0.contains(value) }) { bits |= 1 }
    // Zero columns: default-ignorable code points, combining marks that do not space, and the Hangul Jamo
    // vowels and finals that join a leading consonant (measured: ghostty, wezterm and Terminal.app give 0).
    switch properties.generalCategory {
        case .nonspacingMark, .enclosingMark: bits |= 2
        default: break
    }
    if properties.isDefaultIgnorableCodePoint || (0x1160 ... 0x11FF).contains(value)
        || (0xD7B0 ... 0xD7FF).contains(value)
    {
        bits |= 2
    }
    if properties.isEmojiPresentation { bits |= 4 }
    if properties.isEmoji { bits |= 8 }
    return bits
}

var runs: [(start: UInt32, end: UInt32, bits: UInt8)] = []
var value: UInt32 = 0
while value <= 0x10FFFF {
    let bits = classes(value)
    if bits != 0 {
        if let last = runs.last, last.bits == bits, last.end == value - 1 {
            runs[runs.count - 1].end = value
        } else {
            runs.append((value, value, bits))
        }
    }
    value += 1
}

func hex(_ value: UInt32) -> String { "0x" + String(value, radix: 16, uppercase: true) }
